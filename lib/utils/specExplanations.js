    if (key.includes('BATAREYA') || key.includes('BATTERY') || key.includes('AKKUMLYATOR')) return specExplanations["BATTERY"];
    if (key.includes('ZARYADLASH') || key.includes('CHARGING') || key.includes('CHARGE')) return specExplanations["CHARGING"];
    if (key.includes('MIKROFON') || key.includes('MICROPHONE') || key.includes(' MIC')) return specExplanations["MICROPHONE"];
    if (key.includes('CHASTOTA') || key.includes('FREQUENCY') || key.includes('FREQ') || key.includes('DIAPAZON')) return specExplanations["FREQUENCY"];
    if (key.includes('SHOVQIN') || key.includes('NOISE') || key.includes('ANC') || key.includes('CANCELL')) return specExplanations["NOISE CANCELLATION"];
    if (key.includes('KABEL') || key.includes('CABLE') || key.includes('CORD') || key.includes('PARACORD')) return specExplanations["CABLE"];
    if (key.includes('TUGMA') || key.includes('BUTTON') || key.includes('TUGMALAR SONI') || key.includes('PROGRAMMABLE')) return specExplanations["BUTTONS"];
    if (key.includes('DASTUR') || key.includes('SOFTWARE') || key.includes('DRIVER')) return specExplanations["SOFTWARE"];
    if (key.includes('SENSOR') || key.includes('TRACKING') || key.includes('OPTICAL') || key.includes('LASER')) return specExplanations["SENSOR"];
    if (key.includes('POLLING') || key.includes('REPORT RATE') || key.includes('SOROVLAR')) return specExplanations["POLLING RATE"];
    if (key.includes('RGB') || key.includes('YORITISH') || key.includes('LIGHTING') || key.includes('LED')) return specExplanations["RGB"];
