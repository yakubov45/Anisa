export function getSpecExplanation(specName) {
    if (!specName) return null;
    const key = specName.toString().trim().toUpperCase();
    
    // Core check
    if (key.includes('CPU') || key.includes('PROTSESSOR')) return specExplanations["CPU"];
    if (key.includes('GPU') || key.includes('VIDEOKARTA') || key.includes('VGA')) return specExplanations["GPU"];
    if (key.includes('RAM') || (key.includes('XOTIRA') && key.includes('TEZKOR')) || key.includes('MEMORY')) return specExplanations["RAM"];
    if (key.includes('STORAGE') || key.includes('SSD') || key.includes('HDD') || key.includes('NVME') || (key.includes('XOTIRA') && !key.includes('TEZKOR'))) return specExplanations["STORAGE"];
    if (key.includes('MOTHERBOARD') || key.includes('ONA PLATA') || key.includes('MOBO') || key.includes('PLATA')) return specExplanations["MOTHERBOARD"];
    if (key.includes('POWER') || key.includes('QUVVAT') || key.includes('PSU') || key.includes('BLOK') || key.includes('WATTAGE')) return specExplanations["PSU"];
    if (key.includes('COOLER') || key.includes('SOVUTISH') || key.includes('AIO') || key.includes('COOLING')) return specExplanations["COOLER"];
    if (key.includes('CASE') || key.includes('KORPUS')) return specExplanations["CASE"];
    
    // Peripherals check
    if (key.includes('REFRESH RATE') || key.includes('YANGILANISH') || key.includes('HZ')) return specExplanations["REFRESH RATE"];
    if (key.includes('RESPONSE TIME') || key.includes('JAVOB VAQTI') || key.includes('MS')) return specExplanations["RESPONSE TIME"];
    if (key.includes('RESOLUTION') || key.includes('RUXSAT') || key.includes('PIKSEL')) return specExplanations["RESOLUTION"];
    if (key.includes('PANEL') || key.includes('IPS') || key.includes('VA') || key.includes('TN')) return specExplanations["PANEL TYPE"];
    if (key.includes('DPI') || key.includes('POLLING RATE') || key.includes('SEZUVCHANLIK') || key.includes('SENSOR')) return specExplanations["DPI"];
    if (key.includes('SWITCH') || key.includes('SVICH')) return specExplanations["SWITCH TYPE"];
    if (key.includes('FORM FACTOR') || key.includes('SIZE FORMAT') || key.includes('LAYOUT') || key.includes('O\'LCHAM')) return specExplanations["FORM FACTOR"];
    if (key.includes('WARRANTY') || key.includes('KAFOLAT')) return specExplanations["WARRANTY"];

    return {
        uz: "Bu ushbu qurilmaning o'ziga xos texnik xususiyatlaridan biridir.",
        ru: "Это одна из отличительных технических характеристик данного устройства.",
        en: "This is one of the distinct technical specifications of this device."
    };
}
