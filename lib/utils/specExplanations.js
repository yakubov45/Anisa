    if (key.includes('POWER') || key.includes('QUVVAT') || key.includes('PSU') || key.includes('WATTAGE')) return specExplanations["PSU"];
    if (key.includes('COOLER') || key.includes('SOVUTISH') || key.includes('AIO') || key.includes('COOLING')) return specExplanations["COOLER"];
    if (key.includes('CASE') || key.includes('KORPUS')) return specExplanations["CASE"];

    if (key.includes('OG\'IRLIK') || key.includes('WEIGHT') || key.includes('GRAM') || key.includes('VES')) return specExplanations["WEIGHT"];
