export function translateSpec(keyOrValue, lang) {
    if (!keyOrValue && typeof keyOrValue !== 'boolean' && keyOrValue !== 0) return keyOrValue;
    
    // Check boolean directly
    if (typeof keyOrValue === 'boolean') {
        return keyOrValue ? specDict["Yes"][lang] : specDict["No"][lang];
    }
    
    // For strings and numbers
    const str = String(keyOrValue);
    
    // Check exact match
    if (specDict[str] && specDict[str][lang]) {
        return specDict[str][lang];
    }

    // Try parsing comma separated values
    if (str.includes(',') && !str.match(/^\d+,\d+$/)) { // don't split simple decimals
        return str.split(',').map(part => {
            const p = part.trim();
            if (specDict[p] && specDict[p][lang]) {
                return specDict[p][lang];
            }
            return p;
        }).join(', ');
    }
    
    return str;
}
